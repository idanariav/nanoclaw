function parseCsv(text: string | undefined): Record<string, string>[] {
  if (!text || !text.trim()) return [];
  return parse(text, { columns: true, skip_empty_lines: true, trim: true }) as Record<string, string>[];
}

/** `<Full Name>+<fee>,<role>` — the workbook's own packed format for a משתתף N field. */
function parseParticipant(packed: string): { name: string; fee: string; role: string } | undefined {
  const m = /^(.*)\+([^,]*),(.*)$/.exec(packed);
  return m ? { name: m[1], fee: m[2], role: m[3] } : undefined;
}

function serializeParticipant(p: { name: string; fee: string; role: string }): string {
  return `${p.name}+${p.fee},${p.role}`;
}

export function snapshotToCsvFiles(snapshot: MonthlyReportSnapshot): Record<string, string> {
  const detailsBySlot = new Map(snapshot.eventDetails.map((d) => [d.slot, d]));

  const eventsRows = snapshot.summaryRows.map(({ slot, values }) => {
    const detail = detailsBySlot.get(slot);
    const row: Record<string, string> = { slot: String(slot) };
    for (const h of EVENT_SUMMARY_HEADERS) row[h] = values[h] ?? '';
    row.note = detail?.note ?? '';
    row.commission_total = detail?.commissionTotal ?? '';
    row.complimentary_price = detail?.complimentary.price ?? '';
    row.complimentary_qty = detail?.complimentary.quantity ?? '';
    row.venue_payment_title = detail?.venuePaymentTitle ?? '';
    return row;
  });

  const participantsRows: Record<string, string>[] = [];
  for (const { slot, values } of snapshot.summaryRows) {
    for (let i = 1; i <= NUM_PARTICIPANT_SLOTS; i++) {
      const packed = values[`משתתף ${i}`];
      const parsed = packed ? parseParticipant(packed) : undefined;
      if (!parsed) continue;
      participantsRows.push({ slot: String(slot), index: String(i), ...parsed });
    }
  }

  const artistsRows = snapshot.artists.map((a) => ({ name: a.name, id: a.id, status: a.status, email: a.email }));

  const ticketRows: Record<string, string>[] = [];
  for (const d of snapshot.eventDetails) {
    for (const channel of TICKET_CHANNELS) {
      d.ticketSummary[channel].forEach((line, i) => {
        if (!line.price && !line.quantity) return;
        ticketRows.push({ slot: String(d.slot), channel, line: String(i + 1), price: line.price, quantity: line.quantity });
      });
    }
  }

  const venueRows: Record<string, string>[] = [];
  for (const d of snapshot.eventDetails) {
    d.venuePaymentRows.forEach((row, r) => {
      row.forEach((value, c) => {
        if (!value) return;
        venueRows.push({ slot: String(d.slot), row: String(r + 1), col: String(c + 1), value });
      });
    });
  }

  const monthliesRows = snapshot.monthlies.map((m) => ({
    name: m.name,
    role: m.role,
    payment_type: m.paymentType,
    detail: m.detail,
    id_number: m.idNumber,
    status: m.status,
    salary: m.salary,
  }));

  return {
    'events.csv': stringify(eventsRows, { header: true, columns: EVENTS_COLUMNS }),
    'participants.csv': stringify(participantsRows, { header: true, columns: PARTICIPANTS_COLUMNS }),
    'artists.csv': stringify(artistsRows, { header: true, columns: ARTISTS_COLUMNS }),
    'ticket_summary.csv': stringify(ticketRows, { header: true, columns: TICKET_SUMMARY_COLUMNS }),
    'venue_payment.csv': stringify(venueRows, { header: true, columns: VENUE_PAYMENT_COLUMNS }),
    'monthlies.csv': stringify(monthliesRows, { header: true, columns: MONTHLIES_COLUMNS }),
    'README.md': CSV_README,
  };
}

export interface CsvToChangesResult {
  changes: MonthlyReportChangesJson;
  /** Which slot each blank/placeholder events.csv row resolved to — keyed by the row's own slot token (or "row N" for a truly blank one), for reporting back to the agent. */
  slotAssignments: Record<string, number>;
}

/** Converts the CSV file contents (as read from disk) back into the host's MonthlyReportChanges JSON, resolving any new-event placeholder slots against `usedSlots` (the currently-used slots from a fresh read). */
export function csvFilesToChanges(files: Record<string, string>, usedSlots: number[]): CsvToChangesResult {
  const used = new Set(usedSlots);
  const slotAssignments: Record<string, number> = {};

  function resolveToken(token: string): number {
    if (/^\d+$/.test(token)) return Number(token);
    if (token in slotAssignments) return slotAssignments[token];
    let candidate = 1;
    while (used.has(candidate)) candidate++;
    used.add(candidate);
    slotAssignments[token] = candidate;
    return candidate;
  }

  const eventsRows = parseCsv(files['events.csv']);
  const summaryValuesBySlot = new Map<number, string[]>();
  const noteBySlot = new Map<number, string>();
  const commissionBySlot = new Map<number, string>();
  const complimentaryBySlot = new Map<number, { price: string; quantity: string }>();
  const venueTitleBySlot = new Map<number, string>();

  eventsRows.forEach((row, i) => {
    const token = (row.slot ?? '').trim() || `row ${i + 2}`; // +2: 1-based, plus the header row
    const slot = resolveToken(token);
    summaryValuesBySlot.set(slot, [...EVENT_SUMMARY_HEADERS.map((h) => (row[h] ?? '').trim()), ...new Array(NUM_PARTICIPANT_SLOTS).fill('')]);
    if (row.note) noteBySlot.set(slot, row.note);
    if (row.commission_total) commissionBySlot.set(slot, row.commission_total);
    if (row.complimentary_price || row.complimentary_qty) {
      complimentaryBySlot.set(slot, { price: row.complimentary_price ?? '', quantity: row.complimentary_qty ?? '' });
    }
    if (row.venue_payment_title) venueTitleBySlot.set(slot, row.venue_payment_title);
  });

  for (const row of parseCsv(files['participants.csv'])) {
    const slot = resolveToken((row.slot ?? '').trim());
    const values = summaryValuesBySlot.get(slot);
    if (!values) continue; // participant row referencing a slot events.csv never declared — skip rather than guess
    const index = Number(row.index);
    if (!Number.isInteger(index) || index < 1 || index > NUM_PARTICIPANT_SLOTS) continue;
    values[EVENT_SUMMARY_HEADERS.length + index - 1] = serializeParticipant({
      name: row.name ?? '',
      fee: row.fee ?? '',
      role: row.role ?? '',
    });
  }

  const ticketSummaryBySlot = new Map<number, NonNullable<NonNullable<MonthlyReportChangesJson['eventSheetEdits']>[number]['ticketSummary']>>();
  for (const row of parseCsv(files['ticket_summary.csv'])) {
    const slot = resolveToken((row.slot ?? '').trim());
    const channel = row.channel as TicketChannel;
    if (!TICKET_CHANNELS.includes(channel)) continue;
    const line = Number(row.line);
    if (!Number.isInteger(line) || line < 1 || line > 3) continue;
    const ticketSummary = ticketSummaryBySlot.get(slot) ?? {};
    const lines = ticketSummary[channel] ?? [];
    lines[line - 1] = { price: row.price ?? '', quantity: row.quantity ?? '' };
    ticketSummary[channel] = lines;
    ticketSummaryBySlot.set(slot, ticketSummary);
  }

  const venueRowsBySlot = new Map<number, (string | undefined)[][]>();
  for (const row of parseCsv(files['venue_payment.csv'])) {
    const slot = resolveToken((row.slot ?? '').trim());
    const r = Number(row.row);
    const c = Number(row.col);
    if (!Number.isInteger(r) || r < 1 || r > 6 || !Number.isInteger(c) || c < 1 || c > 4) continue;
    const rows = venueRowsBySlot.get(slot) ?? [];
    rows[r - 1] = rows[r - 1] ?? [];
    rows[r - 1][c - 1] = row.value ?? '';
    venueRowsBySlot.set(slot, rows);
  }

  const eventRows = [...summaryValuesBySlot.entries()]
    .sort(([a], [b]) => a - b)
    .map(([slot, values]) => ({ slot, values }));

  const eventSheetEditSlots = new Set([
    ...noteBySlot.keys(),
    ...commissionBySlot.keys(),
    ...complimentaryBySlot.keys(),
    ...venueTitleBySlot.keys(),
    ...ticketSummaryBySlot.keys(),
    ...venueRowsBySlot.keys(),
  ]);
  const eventSheetEdits = [...eventSheetEditSlots]
    .sort((a, b) => a - b)
    .map((slot) => {
      const ticketSummary = ticketSummaryBySlot.get(slot);
      const commissionTotal = commissionBySlot.get(slot);
      const complimentary = complimentaryBySlot.get(slot);
      const combinedTicketSummary =
        ticketSummary || commissionTotal !== undefined || complimentary
          ? { ...ticketSummary, commissionTotal, complimentary }
          : undefined;
      const venueRows = venueRowsBySlot.get(slot);
      const venueTitle = venueTitleBySlot.get(slot);
      const venuePayment = venueRows || venueTitle !== undefined ? { title: venueTitle, rows: venueRows } : undefined;
      return { slot, note: noteBySlot.get(slot), ticketSummary: combinedTicketSummary, venuePayment };
    });

  const artists = parseCsv(files['artists.csv']).map((row) => ({
    name: row.name ?? '',
    id: row.id || undefined,
    status: row.status || undefined,
    email: row.email || undefined,
  }));

  return {
    changes: {
      artists: artists.length ? artists : undefined,
      eventRows: eventRows.length ? eventRows : undefined,
      eventSheetEdits: eventSheetEdits.length ? eventSheetEdits : undefined,
    },
    slotAssignments,
  };
}
