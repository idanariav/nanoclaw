/**
 * Pure CSV <-> JSON translation for the monthly report tools (no I/O — file writes/reads happen
 * in local-monthly-report-mcp.ts). This is the layer that lets the agent work entirely in CSVs:
 * `snapshotToCsvFiles` turns the host's read-result JSON into named CSV file contents,
 * `csvFilesToChanges` turns edited CSVs back into the host's write-request JSON. The host's own
 * `applyMonthlyReportChangesToBytes` (src/gmail-sanitizer/monthly-report.ts) now auto-renames/
 * reorders/re-syncs on every write, so this layer never needs to think about sheet identity —
 * only slot, which stays stable across renames/reorders (see that file's own comments).
 */
import { parse } from 'csv-parse/sync';
import { stringify } from 'csv-stringify/sync';

export const EVENT_SUMMARY_HEADERS = [
  'תאריך',
  'יישוב',
  'מקום',
  'מפיק',
  'הצגה',
  'גורם מזמין',
  'קהל',
  'שעה',
  'סך דרישה',
  'עבור',
  'כתובת',
  'מייל',
  'איש קשר',
  'טלפון',
] as const;

const NUM_PARTICIPANT_SLOTS = 18;
export const PARTICIPANT_ROLES = ['מנחה', 'חימום', 'מוזיקאי', 'משורר', 'משוררת'] as const;
const TICKET_CHANNELS = ['cash', 'dayOfCredit', 'presaleViaVenue', 'presale'] as const;
type TicketChannel = (typeof TICKET_CHANNELS)[number];

const EVENTS_COLUMNS = [
  'slot',
  ...EVENT_SUMMARY_HEADERS,
  'note',
  'commission_total',
  'complimentary_price',
  'complimentary_qty',
  'venue_payment_title',
];
const PARTICIPANTS_COLUMNS = ['slot', 'index', 'name', 'fee', 'role'];
const ARTISTS_COLUMNS = ['name', 'id', 'status', 'email'];
const TICKET_SUMMARY_COLUMNS = ['slot', 'channel', 'line', 'price', 'quantity'];
const VENUE_PAYMENT_COLUMNS = ['slot', 'row', 'col', 'value'];
const MONTHLIES_COLUMNS = ['name', 'role', 'payment_type', 'detail', 'id_number', 'status', 'salary'];

// --- Wire-format types — mirror src/gmail-sanitizer/monthly-report.ts's JSON shapes exactly; not
// imported directly since the host (Node) and this container (Bun) are separate package trees
// with no shared module boundary — the two DBs / this HTTP call are the only contract between them.

export interface MonthlyReportSnapshot {
  eventSheets: { slot: number | null; name: string }[];
  summaryRows: { slot: number; values: Record<string, string> }[];
  artists: {
    row: number;
    name: string;
    id: string;
    status: string;
    email: string;
    payeeName: string;
    payeeType: string;
    payeeEmail: string;
    amount: string;
  }[];
  monthlies: {
    row: number;
    name: string;
    role: string;
    paymentType: string;
    detail: string;
    idNumber: string;
    status: string;
    salary: string;
  }[];
  eventDetails: {
    slot: number;
    note: string;
    ticketSummary: Record<TicketChannel, { price: string; quantity: string }[]>;
    commissionTotal: string;
    complimentary: { price: string; quantity: string };
    venuePaymentTitle: string;
    venuePaymentRows: string[][];
  }[];
}

export interface MonthlyReportChangesJson {
  artists?: { name: string; id?: string; status?: string; email?: string }[];
  eventRows?: { slot: number; values: string[] }[];
  eventSheetEdits?: {
    slot: number;
    ticketSummary?: {
      cash?: { price?: string; quantity?: string }[];
      dayOfCredit?: { price?: string; quantity?: string }[];
      presaleViaVenue?: { price?: string; quantity?: string }[];
      presale?: { price?: string; quantity?: string }[];
      commissionTotal?: string;
      complimentary?: { price?: string; quantity?: string };
    };
    venuePayment?: { title?: string; rows?: (string | undefined)[][] };
    note?: string;
  }[];
}

